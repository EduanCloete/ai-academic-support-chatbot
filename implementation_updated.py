def compute_hybrid_confidence_vectorized(query_vectors, model):
    """
    Computes Hybrid Confidence = Softmax Probability * Max Cosine Similarity.
    Vectorized for Keras 3 and 2D NumPy matrices.
    """
    query_matrix = np.atleast_2d(np.array(query_vectors, dtype=np.float32))

    # 1. Cosine similarity against verified syllabus corpus
    cos_sims = cosine_similarity(query_matrix, X_embeddings)
    max_cos_sims = np.max(cos_sims, axis=1)

    # 2. Neural categorical prediction probabilities
    probs_tensor = model(query_matrix, training=False)
    probs = probs_tensor.numpy()
    max_softmax = np.max(probs, axis=1)
    max_indices = np.argmax(probs, axis=1)

    # 3. Guardrail confidence score
    hybrid_scores = max_softmax * max_cos_sims
    return hybrid_scores, max_indices

