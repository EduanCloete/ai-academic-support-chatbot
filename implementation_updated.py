# Convert Romanian GPA intervals ('7.5-7.9', '8.0-8.4', etc.) to midpoints
def parse_gpa(val):
    if pd.isna(val):
        return np.nan
    val_str = str(val).strip().replace(',', '.')
    if '-' in val_str:
        parts = val_str.split('-')
        try:
            return (float(parts[0]) + float(parts[1])) / 2.0
        except ValueError:
            return np.nan
    try:
        return float(val_str)
    except ValueError:
        return np.nan

